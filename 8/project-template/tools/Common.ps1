Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

function Get-ProjectRoot {
    return (Split-Path -Parent $PSScriptRoot)
}

function Resolve-ProjectPath {
    param(
        [string] $Path,
        [string] $DefaultRelativePath = '.'
    )

    $candidate = $Path
    if ([string]::IsNullOrWhiteSpace($candidate)) {
        $candidate = $DefaultRelativePath
    }

    if (-not [System.IO.Path]::IsPathRooted($candidate)) {
        $candidate = Join-Path (Get-ProjectRoot) $candidate
    }

    return [System.IO.Path]::GetFullPath($candidate)
}

function Resolve-OneCExecutable {
    param(
        [string] $ExplicitPath,
        [switch] $IgnoreProjectSetting
    )

    $candidate = $ExplicitPath
    if ([string]::IsNullOrWhiteSpace($candidate)) {
        $candidate = $env:ONEC_EXE
    }

    if ([string]::IsNullOrWhiteSpace($candidate) -and -not $IgnoreProjectSetting) {
        $settingPath = Join-Path (Get-ProjectRoot) '.codex/onec-path.txt'
        if (Test-Path -LiteralPath $settingPath -PathType Leaf) {
            $settingLines = @(Get-Content -LiteralPath $settingPath -Encoding UTF8)
            if ($settingLines.Count -ge 2 -and $settingLines[0] -eq '# Generated by onec-project-template setup.ps1; rerun setup after moving the folder.') {
                $candidate = $settingLines[1]
            }
        }
    }

    if (-not [string]::IsNullOrWhiteSpace($candidate)) {
        if (-not (Test-Path -LiteralPath $candidate -PathType Leaf)) {
            throw "1cv8.exe was not found at the specified path: $candidate"
        }
        return (Resolve-Path -LiteralPath $candidate).Path
    }

    $roots = @()
    foreach ($base in @($env:ProgramFiles, ${env:ProgramFiles(x86)})) {
        if (-not [string]::IsNullOrWhiteSpace($base)) {
            $root = Join-Path $base '1cv8'
            if (Test-Path -LiteralPath $root -PathType Container) {
                $roots += $root
            }
        }
    }

    $found = foreach ($root in $roots) {
        Get-ChildItem -LiteralPath $root -Filter '1cv8.exe' -File -Recurse -ErrorAction SilentlyContinue
    }

    $selected = $found |
        Sort-Object -Property @{ Expression = { try { [version] $_.VersionInfo.FileVersion } catch { [version] '0.0.0.0' } } } -Descending |
        Select-Object -First 1

    if ($null -eq $selected) {
        throw '1cv8.exe was not found. Install the platform or pass -OneCExecutable/ONEC_EXE.'
    }

    return $selected.FullName
}

function Resolve-InfoBasePath {
    param([string] $ExplicitPath)

    $candidate = $ExplicitPath
    if ([string]::IsNullOrWhiteSpace($candidate)) {
        $candidate = $env:ONEC_INFOBASE_PATH
    }

    return Resolve-ProjectPath -Path $candidate -DefaultRelativePath 'var\ib'
}

function Resolve-UserName {
    param([string] $Explicit)

    if (-not [string]::IsNullOrWhiteSpace($Explicit)) {
        return $Explicit
    }
    if (-not [string]::IsNullOrWhiteSpace($env:ONEC_USER)) {
        return $env:ONEC_USER
    }

    return 'Администратор'
}

function Get-AuthenticationArguments {
    param(
        [string] $UserName,
        [string] $Password
    )

    $result = @()
    if (-not [string]::IsNullOrWhiteSpace($UserName)) {
        $result += "/N$UserName"
    }
    if (-not [string]::IsNullOrWhiteSpace($Password)) {
        $result += "/P$Password"
    }
    return $result
}

function ConvertTo-NativeArguments {
    param([Parameter(Mandatory)] [string[]] $Arguments)

    return @($Arguments | ForEach-Object {
        if ($_ -match '[\s"]') {
            '"' + ($_ -replace '"', '\"') + '"'
        }
        else {
            $_
        }
    })
}

function Invoke-OneC {
    param(
        [Parameter(Mandatory)] [string] $Executable,
        [Parameter(Mandatory)] [string[]] $Arguments,
        [Parameter(Mandatory)] [string] $LogPath
    )

    $logDirectory = Split-Path -Parent $LogPath
    New-Item -ItemType Directory -Force -Path $logDirectory | Out-Null

    if (Test-Path -LiteralPath $LogPath) {
        Remove-Item -LiteralPath $LogPath -Force
    }

    $allArguments = @($Arguments) + @('/DisableStartupMessages', '/DisableStartupDialogs', '/Out', $LogPath)
    $escapedArguments = ConvertTo-NativeArguments $allArguments

    $process = Start-Process -FilePath $Executable -ArgumentList $escapedArguments -WorkingDirectory (Get-ProjectRoot) -Wait -PassThru -WindowStyle Hidden
    if ($process.ExitCode -ne 0) {
        $details = if (Test-Path -LiteralPath $LogPath) { Get-Content -LiteralPath $LogPath -Raw } else { 'The log file was not created.' }
        throw "1C command failed with exit code $($process.ExitCode).`n$details"
    }
}
