[CmdletBinding()]
param(
    [string] $JavaExecutable,
    [string] $OneCExecutable
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
. (Join-Path $PSScriptRoot 'tools/Common.ps1')

# Only files bearing this marker may be replaced on subsequent setup runs.
$marker = '# Generated by onec-project-template setup.ps1; rerun setup after moving the folder.'
$configDirectory = Join-Path $PSScriptRoot '.codex'
$configPath = Join-Path $configDirectory 'config.toml'
$platformPath = Join-Path $configDirectory 'onec-path.txt'
foreach ($path in @($configPath, $platformPath)) {
    if (Test-Path -LiteralPath $path) {
        if (-not (Test-Path -LiteralPath $path -PathType Leaf)) {
            throw "Expected a file: $path"
        }
        $firstLine = Get-Content -LiteralPath $path -Encoding UTF8 -TotalCount 1
        if ($firstLine -ne $marker) {
            throw "Existing file is not managed by this setup: $path. Preserve it and merge settings manually, or move it before rerunning setup."
        }
    }
}

if ([string]::IsNullOrWhiteSpace($JavaExecutable)) {
    if (-not [string]::IsNullOrWhiteSpace($env:JAVA_HOME)) {
        $javaHomeExecutable = Join-Path $env:JAVA_HOME 'bin/java.exe'
        if (Test-Path -LiteralPath $javaHomeExecutable -PathType Leaf) {
            $JavaExecutable = $javaHomeExecutable
        }
    }
    if ([string]::IsNullOrWhiteSpace($JavaExecutable)) {
        $javaCommand = Get-Command java.exe -CommandType Application -ErrorAction SilentlyContinue | Select-Object -First 1
        if ($null -ne $javaCommand) {
            $JavaExecutable = $javaCommand.Source
        }
    }
}
if ([string]::IsNullOrWhiteSpace($JavaExecutable) -or -not (Test-Path -LiteralPath $JavaExecutable -PathType Leaf)) {
    throw 'Java was not found. Install JDK 25 separately, then rerun .\setup.ps1 -JavaExecutable "C:\path\to\bin\java.exe".'
}
$javaPath = (Resolve-Path -LiteralPath $JavaExecutable).Path

# Ignore the path from a previous setup: the folder may have moved to another PC.
try {
    $oneCPath = Resolve-OneCExecutable -ExplicitPath $OneCExecutable -IgnoreProjectSetting
}
catch {
    throw ('1C platform was not found. Install the platform version required by your configuration, then rerun .\setup.ps1 -OneCExecutable "C:\path\to\bin\1cv8.exe". Details: ' + $_.Exception.Message)
}

$jarPath = Join-Path $PSScriptRoot 'var/tools/bsl-language-server/bsl-language-server-1.0.7-exec.jar'
$vanessaPath = Join-Path $PSScriptRoot 'var/tools/vanessa-automation/vanessa-automation-single.epf'
foreach ($payloadPath in @($jarPath, $vanessaPath)) {
    if (-not (Test-Path -LiteralPath $payloadPath -PathType Leaf)) {
        throw "Template payload is missing: $payloadPath. Copy the complete template and rerun setup."
    }
}

function ConvertTo-TomlString {
    param([string] $Value)
    # JSON basic string escaping is compatible with TOML for Windows paths.
    return ConvertTo-Json -InputObject ($Value.Replace('\', '/')) -Compress
}

$javaToml = ConvertTo-TomlString $javaPath
$jarToml = ConvertTo-TomlString $jarPath
$rootToml = ConvertTo-TomlString $PSScriptRoot
$configuration = @"
$marker
[mcp_servers.bsl-language-mcp]
command = $javaToml
args = ['-Xmx2g', '-jar', $jarToml, 'mcp']
cwd = $rootToml
startup_timeout_sec = 120
tool_timeout_sec = 120
"@

foreach ($directory in @('.codex', 'src/cf', 'src/cfe', 'var/ib', 'var/logs', 'var/templates', 'releases')) {
    New-Item -ItemType Directory -Path (Join-Path $PSScriptRoot $directory) -Force | Out-Null
}
$utf8 = New-Object System.Text.UTF8Encoding($false)
[System.IO.File]::WriteAllText($configPath, $configuration + [Environment]::NewLine, $utf8)
[System.IO.File]::WriteAllText($platformPath, $marker + [Environment]::NewLine + $oneCPath + [Environment]::NewLine, $utf8)

Write-Host "Project tools configured in: $PSScriptRoot"
Write-Host "Java: $javaPath"
Write-Host "1C: $oneCPath"
Write-Host 'Open a new Codex session in this trusted project to connect BSL MCP.'
Write-Host 'Add your configuration or .dt template separately. No infobase was created or changed.'
